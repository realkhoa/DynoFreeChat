/**
 * @file stage.ts
 * @brief Generic game document: one panel that hosts whichever game is open.
 * @details The stage owns the tab chrome (file name, restart button, status
 * line) and swaps the mounted module. Games never touch the tab strip, so the
 * games hub stays the single entry point. A Focus toggle hides every comment and
 * counter the games print, leaving just the generated data literal, which is what
 * makes the document read as a normal source file.
 */

import type { GameContext, GameFactory, GameMount } from "./mount";

/** Storage key remembering the Focus toggle. */
export const FOCUS_STORAGE_KEY = "dyno.game.focus";

/** Trailing code printed after the generated board literal. */
const FOOTER_LINES = [
  "};",
  "",
  "// Compile-time guards for the generated snapshot.",
  'static_assert(sizeof(g_Board) / sizeof(g_Board[0]) == kCellCount, "board snapshot must be dense");',
  'static_assert(kCellCount > 0, "board snapshot must not be empty");',
  "",
  "// Reads one generated cell. Callers validate the index first.",
  "inline CellState ReadCell(std::size_t index) noexcept {",
  "  return static_cast<CellState>(g_Board[index].state);",
  "}",
  "",
  "// Refreshes the generated board snapshot from the live document.",
  "static int RefreshBoardSnapshot() {",
  "  return static_cast<int>(kCellCount);",
  "}",
  "",
  "// Diagnostics counters printed by the status bar.",
  "static const std::uint32_t g_RefreshTicks = 0;",
  "static const std::uint32_t g_WriteCount = 0;",
  "",
  "} // namespace DynoFreeChat::Games",
];

/**
 * @brief Builds the code lines printed above the board literal.
 * @param title Document title, e.g. `Caro.cs`.
 * @return One code line per entry.
 */
function headerLines(title: string): string[] {
  const name = title.replace(/\.(cs|cpp)$/i, "");
  return [
    "// =====================================================================",
    `//  DynoFreeChat :: DynoFreeChat.Games.${name}`,
    "//  Copyright (c) DynoFreeChat contributors. MIT License.",
    "//  Generated by the editor host - do not edit this snapshot by hand.",
    "// =====================================================================",
    "#pragma once",
    "",
    "#include <array>",
    "#include <cstddef>",
    "#include <cstdint>",
    "#include <string_view>",
    "",
    '#include "dynofreechat/board.h"',
    '#include "dynofreechat/diagnostics.h"',
    "",
    "namespace DynoFreeChat::Games {",
    "",
    "enum class BoardRevision : std::uint32_t { kCurrent = 7 };",
    "enum class CellState : std::uint8_t { kEmpty = 0, kPlayerOne = 1, kPlayerTwo = 2 };",
    "",
    "static constexpr std::size_t kCellCount = 0;",
    "static constexpr std::uint32_t kSnapshotFlags = 0x00000007;",
    "",
    "// generated state table - refreshed by the editor host",
    "static const BoardCell g_Board[] = {",
  ];
}

/**
 * @brief Renders plain code lines with the editor's comment/preprocessor colours.
 * @param lines Lines to render.
 * @return The code block element.
 */
function codeBlock(lines: string[]): HTMLElement {
  const block = document.createElement("div");
  block.className = "stage-code";
  for (const line of lines) {
    const row = document.createElement("div");
    row.className = "stage-code-line";
    if (line.trimStart().startsWith("//")) row.classList.add("is-comment");
    else if (line.startsWith("#")) row.classList.add("is-pre");
    row.textContent = line;
    block.append(row);
  }
  return block;
}

/**
 * @brief Normalises a game grid to square cells of one shared size.
 * @details Games hard-code `grid-template-columns: repeat(n, 44px)` for their
 * own layout; inside the document that reads as a wide table. The column count
 * is kept, but every track becomes the shared square cell size.
 * @param root Mounted game root.
 */
function squareBoard(root: HTMLElement): void {
  for (const board of root.querySelectorAll<HTMLElement>(".stage-board")) {
    const template = board.style.gridTemplateColumns;
    const repeat = /repeat\(\s*(\d+)\s*,/.exec(template);
    if (repeat === null) continue;
    board.style.gridTemplateColumns = `repeat(${repeat[1]}, var(--stage-cell-size, 20px))`;
  }
}

/** DOM hosts the stage paints into. */
export interface StageElements {
  /** Document panel, used for visibility checks. */
  panel: HTMLElement;
  /** Empty container the active game fills. */
  host: HTMLElement;
  /** Toolbar file name, e.g. `Caro.cs`. */
  title: HTMLElement;
  /** Toolbar chip, e.g. `// generated · read-only`. */
  chip: HTMLElement;
  /** Status bar text. */
  status: HTMLElement;
  /** Restart button. */
  restart: HTMLButtonElement;
  /** Focus toggle: hides the game comments and counters. */
  focus: HTMLButtonElement;
}

/**
 * @brief Owns the single game document and the currently mounted module.
 */
export class GameStage {
  private active: { id: string; mount: GameMount } | null = null;
  private focused = false;
  private cleanups: Array<() => void> = [];

  /**
   * @param elements DOM hosts.
   * @param factories Lazily created game modules keyed by registry id.
   * @param storage Storage for the Focus preference, or `null`.
   */
  constructor(
    private readonly elements: StageElements,
    private readonly factories: Record<string, GameFactory>,
    private readonly storage: Storage | null = null,
  ) {
    elements.restart.addEventListener("click", () => {
      const id = this.active?.id;
      if (id !== undefined) this.open(id, elements.title.textContent ?? id, elements.chip.textContent ?? "");
    });
    elements.focus.addEventListener("click", () => this.toggleFocus());
    this.focused = this.readFocus();
    this.applyFocus();
  }

  /** Registry id of the mounted game, if any. */
  get activeId(): string | null {
    return this.active?.id ?? null;
  }

  /** Whether the game comments and counters are hidden. */
  get isFocused(): boolean {
    return this.focused;
  }

  /**
   * @brief Shows or hides every game comment line, then remembers the choice.
   * @return The new Focus state.
   */
  toggleFocus(): boolean {
    this.focused = !this.focused;
    this.writeFocus();
    this.applyFocus();
    return this.focused;
  }

  /**
   * @brief Mounts one game, replacing whatever was mounted before.
   * @param id Registry id.
   * @param title Document title for the toolbar.
   * @param summary One-line description for the toolbar chip.
   * @param context Optional mount context, e.g. an online bridge.
   * @return Whether the game id is known.
   */
  open(id: string, title: string, summary: string, context?: GameContext): boolean {
    const factory = this.factories[id];
    if (factory === undefined) return false;

    this.unmountActive();
    this.elements.title.textContent = title;
    // The chip must read like an editor banner, not like a game description.
    this.elements.chip.textContent =
      context?.online === undefined ? "// generated · read-only" : "// remote session";
    this.elements.status.textContent = "Ready";
    // Restarting an online game would desync the two boards, so the stage hides
    // the restart control while a bridge is attached.
    this.elements.restart.disabled = context?.online !== undefined;

    const mount = factory();
    this.elements.host.replaceChildren();
    this.cleanups = [];

    // The game renders inside a generated source file: real code lines surround
    // it so the board reads as one data literal among other declarations.
    const frame = document.createElement("div");
    frame.className = "stage-code-frame";
    frame.dataset.summary = summary;
    const inner = document.createElement("div");
    inner.className = "stage-game-host";

    frame.append(codeBlock(headerLines(title)), inner, codeBlock(FOOTER_LINES));
    this.elements.host.append(frame);

    mount.mount(inner, context);
    squareBoard(inner);
    this.active = { id, mount };
    this.applyFocus();
    return true;
  }

  /**
   * @brief Unmounts the active game, if any.
   */
  close(): void {
    this.unmountActive();
  }

  /**
   * @brief Updates the status bar text.
   * @param text Message to show.
   */
  setStatus(text: string): void {
    this.elements.status.textContent = text;
  }

  /** @brief Tears down the active module without touching the panel. */
  private unmountActive(): void {
    for (const dispose of this.cleanups) dispose();
    this.cleanups = [];
    if (this.active === null) return;
    try {
      this.active.mount.unmount();
    } catch {
      // A broken unmount must never block opening the next game.
    }
    this.elements.host.replaceChildren();
    this.active = null;
  }

  /** @brief Paints the Focus state on the host and the toggle button. */
  private applyFocus(): void {
    this.elements.host.dataset.focus = this.focused ? "on" : "off";
    this.elements.focus.classList.toggle("is-active", this.focused);
    this.elements.focus.setAttribute("aria-pressed", String(this.focused));
    this.elements.focus.title = this.focused
      ? "Show the generated comments (Ctrl+Shift+H)"
      : "Hide comments and counters (Ctrl+Shift+H)";
  }

  /**
   * @brief Reads the remembered Focus preference.
   * @return Whether comments should start hidden.
   */
  private readFocus(): boolean {
    if (this.storage === null) return false;
    try {
      return this.storage.getItem(FOCUS_STORAGE_KEY) === "1";
    } catch {
      return false;
    }
  }

  /** @brief Remembers the Focus preference, ignoring blocked storage. */
  private writeFocus(): void {
    if (this.storage === null) return;
    try {
      this.storage.setItem(FOCUS_STORAGE_KEY, this.focused ? "1" : "0");
    } catch {
      // A blocked storage must not break the toggle.
    }
  }
}
