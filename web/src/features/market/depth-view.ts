/**
 * @file depth-view.ts
 * @brief Volume profile document: traded volume per price, dressed as C++.
 * @details The profile comes from the last 24 hours of one-minute candles, so
 * it answers "where did the session actually trade" rather than showing the
 * three-level order book the quote table already has.
 */

import type { DepthLevel } from "@dyno/shared/market";
import { formatTime } from "@/shared/lib/format";
import type { MarketClient } from "./board";

/** Bars used for the inline ASCII volume gauge. */
export const GAUGE_WIDTH = 24;

/** DOM hosts the profile paints into. */
export interface DepthElements {
  panel: HTMLElement;
  content: HTMLElement;
  gutter: HTMLElement;
  symbol: HTMLInputElement;
  openButton: HTMLButtonElement;
  chip: HTMLElement;
  state: HTMLElement;
  clock: HTMLElement;
}

/**
 * @brief Builds the ASCII gauge for one level.
 * @param percent Volume relative to the busiest level, 0-100.
 * @return A filled/empty bar string.
 */
export function gauge(percent: number): string {
  const filled = Math.max(0, Math.min(GAUGE_WIDTH, Math.round((percent / 100) * GAUGE_WIDTH)));
  return "█".repeat(filled) + "░".repeat(GAUGE_WIDTH - filled);
}

/**
 * @brief Formats a share count without separators.
 * @param value Share count.
 * @return The rounded integer as a string.
 */
function formatVolume(value: number): string {
  return Math.round(value).toString();
}

/**
 * @brief Owns the volume profile document.
 */
export class DepthView {
  private symbol = "FPT";
  private levels: DepthLevel[] = [];
  private totalVolume = 0;
  private lastTs = 0;
  private error: string | null = null;
  private inFlight = false;

  /**
   * @param elements DOM hosts.
   * @param client Market proxy client.
   */
  constructor(
    private readonly elements: DepthElements,
    private readonly client: MarketClient,
  ) {
    this.elements.openButton.addEventListener("click", () => this.commitSymbol());
    this.elements.symbol.addEventListener("keydown", (event) => {
      if (event.key !== "Enter") return;
      event.preventDefault();
      this.commitSymbol();
    });
  }

  /** Symbol currently profiled. */
  get currentSymbol(): string {
    return this.symbol;
  }

  /** Levels currently shown. */
  get currentLevels(): DepthLevel[] {
    return [...this.levels];
  }

  /** @brief Paints the empty document and loads the first profile. */
  start(): void {
    this.elements.symbol.value = this.symbol;
    this.render();
    void this.load();
  }

  /** @brief No timer to clear; kept for symmetry with the other views. */
  stop(): void {}

  /**
   * @brief Changes the profiled symbol.
   * @param raw Text from the symbol box.
   */
  setSymbol(raw: string): void {
    const symbol = raw.trim().toUpperCase();
    if (!/^[A-Z0-9]{1,12}$/.test(symbol)) {
      this.error = "// [error] invalid ticker";
      this.render();
      return;
    }
    this.symbol = symbol;
    this.elements.symbol.value = symbol;
    void this.load();
  }

  /**
   * @brief Fetches the profile and repaints.
   * @return Resolves when the repaint is done; never rejects.
   */
  async refresh(): Promise<void> {
    return this.load();
  }

  /** @brief Commits the symbol box. */
  private commitSymbol(): void {
    this.setSymbol(this.elements.symbol.value);
  }

  /** @brief Loads one profile. */
  private async load(): Promise<void> {
    if (this.inFlight) return;
    this.inFlight = true;
    this.elements.state.textContent = "Loading";

    try {
      const payload = await this.client.depth(this.symbol);
      this.levels = payload.levels;
      this.totalVolume = payload.totalVolume;
      this.lastTs = payload.ts;
      this.error = null;
      this.elements.state.textContent = `${payload.levels.length} levels`;
    } catch {
      this.error = "// [error] volume profile unavailable";
      this.elements.state.textContent = "Offline";
    } finally {
      this.inFlight = false;
      this.render();
    }
  }

  /** @brief Repaints the document. */
  private render(): void {
    const { content, gutter } = this.elements;
    content.replaceChildren();

    const header = document.createElement("div");
    header.className = "code-line";
    header.append(comment(`// <auto-generated> DynoFreeChat volume profile - ${this.symbol} (24h session)`));
    content.append(header);

    const profile = document.createElement("div");
    profile.className = "code-line";
    profile.append(span("kw", "struct"), span("ident", ` ${this.symbol}_Profile`), span("kw", " {"));
    content.append(profile);

    const total = document.createElement("div");
    total.className = "code-line indent1";
    total.append(
      span("type", "long"),
      document.createTextNode(" totalVolume = "),
      span("num", formatVolume(this.totalVolume)),
      document.createTextNode(";"),
    );
    content.append(total);

    const open = document.createElement("div");
    open.className = "code-line indent1";
    open.append(span("type", "Level"), document.createTextNode(` levels[${this.levels.length}] = {`));
    content.append(open);

    if (this.levels.length === 0 && this.error === null) {
      const waiting = document.createElement("div");
      waiting.className = "code-line indent2";
      waiting.append(comment("// waiting for the first profile"));
      content.append(waiting);
    }

    for (const level of this.levels) {
      const line = document.createElement("div");
      line.className = "code-line indent2";
      line.append(
        document.createTextNode("{ "),
        span("num", level.price.toFixed(2)),
        document.createTextNode(", "),
        span("num", formatVolume(level.volume)),
        document.createTextNode(", "),
        span("num", `${level.percent.toFixed(1)}%`),
        document.createTextNode(" }, "),
        span("comment", `// ${gauge(level.percent)}`),
      );
      content.append(line);
    }

    const close = document.createElement("div");
    close.className = "code-line indent1";
    close.append(document.createTextNode("};"));
    content.append(close);

    const tail = document.createElement("div");
    tail.className = "code-line";
    tail.append(document.createTextNode("};"), comment(" // struct"));
    content.append(tail);

    if (this.error !== null) {
      const error = document.createElement("div");
      error.className = "code-line";
      error.append(comment(this.error));
      content.append(error);
    }

    const lines = content.querySelectorAll(":scope > .code-line");
    const numbers: HTMLSpanElement[] = [];
    for (let index = 0; index < lines.length; index += 1) {
      const number = document.createElement("span");
      number.textContent = String(index + 1);
      numbers.push(number);
    }
    gutter.replaceChildren(...numbers);

    const symbols = this.levels.length;
    this.elements.chip.textContent = `// profile: ${symbols} ${symbols === 1 ? "level" : "levels"}`;
    this.elements.clock.textContent = this.lastTs > 0 ? formatTime(this.lastTs) : "--:--:--";
  }
}

/**
 * @brief Creates a comment span.
 * @param value Comment text.
 * @return The span element.
 */
function comment(value: string): HTMLSpanElement {
  const element = document.createElement("span");
  element.className = "comment";
  element.textContent = value;
  return element;
}

/**
 * @brief Creates a syntax span.
 * @param className Syntax class.
 * @param value Text content.
 * @return The span element.
 */
function span(className: string, value: string): HTMLSpanElement {
  const element = document.createElement("span");
  element.className = className;
  element.textContent = value;
  return element;
}
